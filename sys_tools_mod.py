def sys_selecting(pl, core, auto):
    """Main menu loop for System Tools."""
    org_delay = core.ui.typing_delay
    core.ui.typing_delay = 0
    core.ui.workdir = "/act/sys/"

    while True:
        core.ui.out([
            "./title",
            "./menu-1",
            "./menu-2",
            "./menu-3",
            "./menu-4",
            "./menu-0",
            "/share/endl"
        ])
        
        choice = core.ui.inp("./prompt-opt").strip()
        
        if choice == "1":
            handle_status(core)
        elif choice == "2":
            Menu_Setting(core.ui, core.BattleEnv, on_save=core.update_status)
            core.ui.workdir = "/act/sys/"
        elif choice == "3":
            lang = ModContents.get("chosen_lang_code", "zh_cn")
            Menu_ModManager(core.ui, core.Mods, lang, is_core=True, on_reload=core.ModsHotReload)
            core.ui.workdir = "/act/sys/"
        elif choice == "4":
            handle_players(core)
        elif choice == "0" or not choice:
            core.ui.out("./exit")
            break
        else:
            core.ui.out("./invalid-choice")

    core.ui.typing_delay = org_delay
    core.ls_acts()
    return (False, None)


