def handle_status(core):
    """Query advanced battlefield and player data."""
    core.ui.workdir = "/act/sys/"
    core.ui.out("./stt-title")

    total_alive = len(core.PlDict)
    total_energy = core.status.get("energy", {}).get("all", sum(p.energy for p in core.PlDict.values()))
    map_limit = core.BattleEnv.get("map", 3)
    core.ui.out("./stt-summary", imp=[total_alive, total_energy, map_limit])

    pop_stats = []
    for place, data in sorted(core.status.get("pop", {}).items(), key=lambda x: str(x[0])):
        if place != "all":
            pop_stats.append(f"{place}F: {len(data.get('sum', []))}")
    core.ui.out("./stt-pop-dist", imp=[", ".join(pop_stats)])

    filter_str = core.ui.inp("./stt-filter-prompt").strip().lower()

    # Retrieve localized header strings
    header_str = core.ui.get("./stt-header")
    header_tuple = tuple(header_str.split(","))
    table_data = [header_tuple]

    for p in core.PlDict.values():
        if filter_str.startswith("t") and filter_str[1:].isdigit():
            if p.team != int(filter_str[1:]): 
                continue
        elif filter_str.startswith("p") and (filter_str[1:].isdigit() or (filter_str[1:].startswith('-') and filter_str[2:].isdigit())):
            if p.place != int(filter_str[1:]): 
                continue

        p_type = core.ui.get("./stt-type-human") if p.real else noah.explain(core.ui.get("./stt-type-ai"), [p.ai_quality])
        stt_list = [k for k, v in p.status.items() if v]
        stt_str = ",".join(stt_list) if stt_list else core.ui.get("./stt-none")
        table_data.append((p.id, p_type, p.team, p.HP, p.energy, p.place, p.outd, len(p.kills), stt_str))

    table_format = f"{C['YELLOW']}$0{C['RESET']}\t$1\t{C['CYAN']}$2{C['RESET']}\t{C['GREEN']}$3{C['RESET']}\t{C['MAGENTA']}$4{C['RESET']}\t$5\t$6\t$7\t$8"
    core.ui.out(noah.table(table_data, table_format), directly=True)
    core.ui.inp("./stt-press-enter")


def handle_players(core):
    """Batch edit active player attributes with mapped localized names."""
    core.ui.workdir = "/act/sys/"
    core.ui.out("./pl-title")
    t_str = core.ui.inp("./pl-prompt-targets").strip()
    if not t_str: 
        return

    targets = parse_target_players(t_str, core)

    if not targets:
        core.ui.out("./pl-err-no-target")
        return

    core.ui.out("./pl-target-count", imp=[len(targets)])
    
    # Map numerical selection to internal attribute keys
    attr_map = {
        "1": "HP",
        "2": "energy",
        "3": "place",
        "4": "team",
        "5": "ai_quality"
    }

    attr_choice = core.ui.inp("./pl-prompt-attr").strip()
    if attr_choice not in attr_map:
        core.ui.out("./pl-err-attr")
        return

    internal_attr = attr_map[attr_choice]
    localized_attr_name = core.ui.get(f"./attr-{attr_choice}")

    val_str = core.ui.inp("./pl-prompt-val", imp=[localized_attr_name]).strip()
    if not val_str: 
        return

    success_count = 0
    for p in targets:
        cur_v = getattr(p, internal_attr, 0)
        try:
            if val_str.startswith("+") or val_str.startswith("-"):
                new_v = cur_v + int(val_str)
            else:
                new_v = int(val_str)
            setattr(p, internal_attr, new_v)
            success_count += 1
        except ValueError:
            core.ui.out("./pl-err-val")
            return

    # Update cache snapshot so AI and system logic immediately see the changes
    core.update_status()
    core.ui.out("./pl-success", imp=[success_count, localized_attr_name])


