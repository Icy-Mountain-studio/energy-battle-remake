def parse_target_players(input_str, core):
    """
    Parses user input into a unique list of existing, alive Player objects.
    Supports ranges ('1-5'), specific IDs ('1,3,7'), teams ('t1'), levels ('p0'), and 'all'.
    """
    raw_str = input_str.strip().lower()
    if not raw_str:
        return []

    if raw_str == "all":
        return list(core.PlDict.values())

    if raw_str.startswith("t") and raw_str[1:].isdigit():
        team_id = int(raw_str[1:])
        return [p for p in core.PlDict.values() if p.team == team_id]

    if raw_str.startswith("p"):
        pos_part = raw_str[1:]
        if pos_part.isdigit() or (pos_part.startswith('-') and pos_part[1:].isdigit()):
            pos_id = int(pos_part)
            return [p for p in core.PlDict.values() if p.place == pos_id]

    matched_ids = []
    tokens = [tk.strip() for tk in raw_str.split(",") if tk.strip()]

    for tk in tokens:
        # Range format logic
        if "-" in tk and not tk.startswith("-"):
            parts = tk.split("-")
            if len(parts) == 2:
                try:
                    start_id = int(parts[0].strip())
                    end_id = int(parts[1].strip())
                    low, high = min(start_id, end_id), max(start_id, end_id)
                    matched_ids.extend(range(low, high + 1))
                except ValueError:
                    continue
        else:
            try:
                matched_ids.append(int(tk))
            except ValueError:
                continue

    # Filter out non-existent players and eliminate duplicates
    seen = set()
    result = []
    for pid in matched_ids:
        if pid in core.PlDict and pid not in seen:
            seen.add(pid)
            result.append(core.PlDict[pid])

    return result


